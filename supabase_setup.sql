-- HUD AI Inspector DEVELOPMENT ONLY. Idempotent schema and policies.
-- Run in the DEVELOPMENT Supabase project SQL editor. Never use real resident data.
create extension if not exists pgcrypto;
create table if not exists public.inspections (
 id uuid primary key default gen_random_uuid(),
 owner_id uuid not null references auth.users(id),
 property text not null, address text, unit text, inspector text,
 inspected_on date, notes text, created_at timestamptz not null default now()
);
create table if not exists public.evidence (
 id uuid primary key default gen_random_uuid(),
 inspection_id uuid not null references public.inspections(id) on delete cascade,
 area text, room text, kind text, path text, source_name text,
 captured_at timestamptz not null default now(),
 findings_json jsonb not null default '[]'::jsonb,
 reviewed_json jsonb not null default '{}'::jsonb
);
create table if not exists public.audit_events (
 id uuid primary key default gen_random_uuid(),
 inspection_id uuid not null references public.inspections(id) on delete cascade,
 actor_id uuid references auth.users(id), event text not null,
 occurred_at timestamptz not null default now()
);
create table if not exists public.inspector_profiles (
 user_id uuid primary key references auth.users(id) on delete cascade,
 username text not null unique,
 created_at timestamptz not null default now(),
 constraint username_format check (username ~ '^[a-z][a-z0-9_]{2,31}$')
);
alter table public.inspections enable row level security;
alter table public.evidence enable row level security;
alter table public.audit_events enable row level security;
alter table public.inspector_profiles enable row level security;
revoke all on public.inspections, public.evidence, public.audit_events, public.inspector_profiles from anon, authenticated;
grant usage on schema public to authenticated;
grant select, insert, update on public.inspections to authenticated;
grant select, insert, update on public.evidence to authenticated;
grant select on public.audit_events to authenticated;
grant select on public.inspector_profiles to authenticated;

