-- Audit is generated by a trigger, not writable by authenticated clients.
create or replace function public.log_evidence_review_change()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
 if new.reviewed_json is distinct from old.reviewed_json then
  insert into public.audit_events (inspection_id,actor_id,event)
  values (new.inspection_id, auth.uid(), 'Inspector review saved: evidence ' || left(new.id::text,12));
 end if;
 return new;
end $$;
revoke all on function public.log_evidence_review_change() from public, anon, authenticated;
drop trigger if exists trg_evidence_review_audit on public.evidence;
create trigger trg_evidence_review_audit after update of reviewed_json on public.evidence
 for each row execute function public.log_evidence_review_change();

